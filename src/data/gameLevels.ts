export function getGameLevels(gameType: GameType): BaseLevelConfig[] {
  switch (gameType) {
    case 'memory_match':
      return MEMORY_MATCH_LEVELS;
    case 'sequence_recall':
      return SEQUENCE_RECALL_LEVELS;
    case 'picture_recognition':
      return PICTURE_RECOGNITION_LEVELS;
    case 'simple_puzzle':
      return SIMPLE_PUZZLE_LEVELS;
    case 'face_match':
      return FACE_MATCH_LEVELS;
    default:
      return MEMORY_MATCH_LEVELS;
  }
}

export function getLevelConfig<T = BaseLevelConfig>(gameType: GameType, levelNumber: number): T {
  const levels = getGameLevels(gameType);
  const found = levels.find((l) => l.level === levelNumber) || levels[0];
  return found as unknown as T;
}
