import { GameType, DifficultyLevel } from '../types';

export interface BaseLevelConfig {
  level: number;
  difficulty: DifficultyLevel;
  title: Record<string, string>;
  description: Record<string, string>;
  winConditionText: Record<string, string>;
  pointsBase: number;
}

export interface MemoryMatchLevelConfig extends BaseLevelConfig {
  pairsCount: number;
  maxAttempts: number;
  previewPeekMs?: number;
  flipBackDelayMs: number;
}

export interface SequenceRecallLevelConfig extends BaseLevelConfig {
  sequenceLength: number;
  roundsCount: number;
  stepIntervalMs: number;
  maxMistakesAllowed: number;
}

export interface PictureRecognitionLevelConfig extends BaseLevelConfig {
  questionsCount: number;
  optionsCount: number;
  minCorrectToPass: number;
  timePerQuestionSec?: number;
}

export interface SimplePuzzleLevelConfig extends BaseLevelConfig {
  gridDimension: 2 | 3; // 2x2 or 3x3
  scrambleSwaps: number;
  maxMoves: number;
  timeLimitSec?: number;
  showGhostHint: boolean;
}

export interface FaceMatchLevelConfig extends BaseLevelConfig {
  roundsCount: number;
  optionsCount: number;
  minCorrectToPass: number;
  timePerQuestionSec?: number;
  mode: 'recognize_name' | 'recognize_relation' | 'mixed';
}

